class BusinessProfile(models.Model):
    """
    The single source of truth for what the bot knows about the business it
    represents — edit this in /admin/ any time, no code changes needed.
    Intended as a singleton: the bot always uses the first row.
    """

    name = models.CharField(max_length=100)
    tagline = models.CharField(max_length=200, blank=True, help_text="One-line description.")
    services = models.TextField(
        help_text="One service per line — this is what stops the bot from "
        "inventing offerings you don't actually provide."
    )
    pricing_note = models.TextField(
        blank=True,
        help_text="Leave blank to have the bot say pricing varies / ask support, "
        "instead of quoting numbers. Fill in only if you want real prices quoted.",
    )
    hours_note = models.CharField(
        max_length=200,
        blank=True,
        help_text="Leave blank to have the bot avoid claiming specific hours.",
    )
    support_contact = models.CharField(
        max_length=50,
        blank=True,
        help_text="Phone number (or similar) given out on human handoff / HELP.",
    )
    do_not_instructions = models.TextField(
        blank=True,
        help_text="Compliance/guardrail rules, e.g. 'never give definitive tax "
        "advice — describe services and fall back to human support instead.'",
    )
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return self.name


class KnowledgeBaseDocument(models.Model):
    """
    A source document (PDF/Word upload, or a web page URL) that gets
    automatically split into KnowledgeBaseEntry chunks — the "document
    loader" that replaces manually retyping document content into entries
    one at a time. Provide either `file` or `source_url`, not both.

    Processing doesn't happen on save (extraction can fail/take a moment) —
    select it in the admin list and run the "Process into knowledge base
    entries" action.
    """

    title = models.CharField(max_length=200, help_text="Label for this source, e.g. 'Refund Policy PDF'.")
    file = models.FileField(
        upload_to="kb_documents/", blank=True,
        help_text="A PDF or Word (.docx) file. Leave blank if using a URL instead.",
    )
    source_url = models.URLField(
        blank=True,
        help_text="A web page to pull text from, instead of a file upload.",
    )
    uploaded_at = models.DateTimeField(auto_now_add=True)
    processed = models.BooleanField(
        default=False,
        help_text="Set automatically once processed into KB entries below.",
    )
    processing_error = models.TextField(
        blank=True, help_text="Set automatically if the last processing attempt failed.",
    )

    def __str__(self):
        return self.title


class KnowledgeBaseEntry(models.Model):
    """
    A small, admin-editable FAQ/policy entry — injected into every free-chat
    reply's system prompt so Gemini answers from this content instead of its
    own general knowledge or guessing. For a handful of entries this is
    simpler and more reliable than a retrieval/embeddings setup; if the KB
    grows large enough to blow past prompt size, that's the point to switch
    to real retrieval instead of stuffing everything in every call.

    Created either by hand, or automatically as one chunk of a
    KnowledgeBaseDocument (see source_document) — either way, this is the
    only table services._build_knowledge_base_context reads from.
    """

    title = models.CharField(max_length=200, help_text="A FAQ question or policy name, e.g. 'Refund policy'.")
    content = models.TextField(help_text="The answer/policy text — the bot is instructed to rely on this faithfully.")
    is_active = models.BooleanField(default=True, help_text="Uncheck to keep an entry without deleting it.")
    order = models.PositiveSmallIntegerField(default=0)
    source_document = models.ForeignKey(
        KnowledgeBaseDocument, on_delete=models.CASCADE, null=True, blank=True,
        related_name="entries",
        help_text="Set automatically for entries generated by the document loader; "
        "blank for entries written by hand.",
    )

    class Meta:
        ordering = ["order", "id"]
        verbose_name_plural = "Knowledge base entries"

    def __str__(self):
        return self.title


