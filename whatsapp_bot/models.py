class ServicePricing(models.Model):
    """
    A single priceable sub-service within a category — the bot only ever
    quotes what's in this table, never a Gemini-generated number.

    question_type controls what (if anything) is asked before quoting:
      - blank:    quote price_display directly.
      - quantity: ask clarifying_question, parse a number from the reply,
                  price = price_per_unit * quantity.
      - topic:    ask clarifying_question, match the reply against
                  topic_options — price stays price_display either way,
                  the topic is just tagged onto the confirmation for
                  whoever picks up the consult.
    """

    QUESTION_NONE = ""
    QUESTION_QUANTITY = "quantity"
    QUESTION_TOPIC = "topic"
    QUESTION_TYPE_CHOICES = [
        (QUESTION_NONE, "None — quote price_display directly"),
        (QUESTION_QUANTITY, "Quantity — price = price_per_unit × quantity"),
        (QUESTION_TOPIC, "Topic — price stays fixed, just tag which topic"),
    ]

    category = models.ForeignKey(ServiceCategory, on_delete=models.PROTECT, related_name="services")
    parent_service = models.ForeignKey(
        "self", on_delete=models.PROTECT, related_name="subservices", null=True, blank=True,
        help_text="Optional parent menu item. Child items appear only after that service is selected.",
    )
    service_code = models.SlugField(unique=True, help_text="e.g. 'itr_salary' — stable identifier, not shown to users.")
    display_name = models.CharField(max_length=100, help_text='e.g. "ITR Salary Filing"')
    short_description = models.CharField(max_length=200, blank=True)
    price_display = models.CharField(
        max_length=200,
        blank=True,
        help_text="e.g. '₹999 onwards'. Leave blank (with question_type=None) to have "
        "the bot offer a human handoff instead of quoting a number.",
    )
    question_type = models.CharField(max_length=10, choices=QUESTION_TYPE_CHOICES, blank=True)
    clarifying_question = models.CharField(
        max_length=300,
        blank=True,
        help_text="Used when question_type is 'quantity' or 'topic'.",
    )
    price_per_unit = models.DecimalField(
        max_digits=10, decimal_places=2, null=True, blank=True,
        help_text="Only used when question_type='quantity'.",
    )
    unit_label = models.CharField(max_length=30, blank=True, help_text="e.g. 'month', 'quarter'.")
    topic_options = models.TextField(blank=True, help_text="One topic per line — only used when question_type='topic'.")
    is_active = models.BooleanField(
        default=True,
        help_text="Uncheck to hide this item from the customer-facing service menu without losing its history.",
    )
    order = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["order", "id"]
        verbose_name_plural = "Service pricing"

    def __str__(self):
        return self.display_name


