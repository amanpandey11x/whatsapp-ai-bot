# SQLite by default (fine for local dev) — set DATABASE_URL to switch to
# Postgres, e.g. postgres://user:pass@host:5432/dbname. This is not optional
# once payments are live: SQLite locks the whole file on every write, and a
# payment webhook landing while a Celery worker is mid-write to the same
# file produces "database is locked" errors — silently dropping a payment
# confirmation that genuinely happened. See requirements.txt for the driver.
if env('DATABASE_URL', default=''):
    DATABASES = {'default': env.db('DATABASE_URL')}
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


